"""Generate sw.js with a precache list of every app asset.

Run this whenever files are ADDED or REMOVED, so the precache list still
matches what is on disk. You no longer have to run it for ordinary edits:
the worker serves the shell network-first, so changed HTML, CSS, JS and
JSON reach installed phones on their next launch whether or not this
script was run. Run it last when you do run it — it stamps a cache
version taken from the contents of every file.
"""
import os as _os
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_ROOT = _os.path.dirname(_HERE)

import hashlib
import json

ROOT = _ROOT

# The app is useless without these, so a failed install must be retried
# rather than leaving a half-cached app that breaks the moment it goes
# offline. Images are best-effort and topped up afterwards.
CRITICAL = ["index.html", "styles.css", "app.js", "config.js",
            "manifest.webmanifest", "data/questions.json", "data/unlock.json"]
DIRS = ["icons", "img"]

assets = list(CRITICAL)
for d in DIRS:
    p = _os.path.join(ROOT, d)
    for f in sorted(_os.listdir(p)):
        if f.lower().endswith((".png", ".webp", ".jpg", ".svg")):
            assets.append(f"{d}/{f}")

h = hashlib.md5()
total = 0
for a in assets:
    fp = _os.path.join(ROOT, a.replace("/", _os.sep))
    with open(fp, "rb") as fh:
        b = fh.read()
    total += len(b)
    h.update(b)
version = h.hexdigest()[:10]

# the template carries JS regexes, so keep it raw
sw = r"""/* Kora Utware — service worker (generated by build/4_service_worker.py).
   Precaches the whole app so it runs with no internet at all. */

const CACHE = 'kora-utware-%(version)s';
/* The app mirrors the licence and trial counters here. It is NOT a
   precache and must survive every upgrade — deleting it would hand a
   paying user back to the paywall. */
const VAULT = 'kora-vault';
const CRITICAL = %(critical)s;
const ASSETS = %(assets)s;

/* Fetch in small batches — a cheap phone choking on 150 parallel
   requests is how a precache half-finishes. */
async function fill(cache, urls, strict) {
  const missing = [];
  for (let i = 0; i < urls.length; i += 8) {
    await Promise.all(urls.slice(i, i + 8).map(async url => {
      try {
        const res = await fetch(url, { cache: 'reload' });
        if (res.ok) await cache.put(url, res);
        else missing.push(url);
      } catch (e) { missing.push(url); }
    }));
  }
  if (strict && missing.length) {
    // Failing the install is deliberate: the browser retries later, which
    // is far better than activating an app that dies offline.
    throw new Error('precache incomplete: ' + missing.join(', '));
  }
  return missing;
}

/* Cache whatever is still missing. Runs on activate and whenever the
   page asks, so a patchy first load repairs itself on the next one. */
async function topUp() {
  const cache = await caches.open(CACHE);
  const missing = [];
  for (const url of ASSETS) {
    if (!(await cache.match(url))) missing.push(url);
  }
  if (missing.length) await fill(cache, missing, false);
  return missing.length;
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await fill(cache, CRITICAL, true);
    await fill(cache, ASSETS.filter(u => !CRITICAL.includes(u)), false);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys
      .filter(k => k !== CACHE && k !== VAULT)
      .map(k => caches.delete(k)));
    await self.clients.claim();
    await topUp();
  })());
});

self.addEventListener('message', event => {
  const msg = event.data || {};
  if (msg.type === 'topup') {
    event.waitUntil(topUp().then(n => {
      event.source && event.source.postMessage({ type: 'topup-done', repaired: n });
    }));
  }
  if (msg.type === 'version') {
    event.source && event.source.postMessage({ type: 'version', cache: CACHE });
  }
  if (msg.type === 'skip-waiting') self.skipWaiting();
});

/* ── fetch strategies ───────────────────────────────────────────────
   The app used to be cache-first for everything, which meant a deploy
   only reached a phone if sw.js itself changed — one forgotten build
   step and the installed app was frozen forever. Now freshness does not
   depend on the worker being rebuilt:

     shell  (html/js/css/json)  network-first, cache is the fallback
     images (img/, icons/)      cache-first, refreshed in the background
     rest                       cache-first, then network

   Offline behaviour is unchanged: every branch ends at the cache.     */

const SHELL_RE = /\.(html|js|css|json|webmanifest)$/i;
const IMAGE_RE = /\.(png|jpe?g|webp|svg|gif|avif)$/i;
const NET_TIMEOUT = 3500;

function withTimeout(promise, ms) {
  return Promise.race([
    promise,
    new Promise((_, reject) => setTimeout(() => reject(new Error('slow network')), ms)),
  ]);
}

/** Always try the network; fall back to whatever we cached last time. */
async function networkFirst(req, key) {
  const cache = await caches.open(CACHE);
  try {
    const res = await withTimeout(fetch(req, { cache: 'no-store' }), NET_TIMEOUT);
    if (!res || !res.ok) throw new Error('bad response');
    await cache.put(key || req, res.clone());
    return res;
  } catch (e) {
    const cached = await cache.match(key || req, { ignoreSearch: true });
    if (cached) return cached;
    throw e;
  }
}

/** Paint instantly from cache, quietly pick up a newer copy for next time. */
async function staleWhileRevalidate(req, event) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(req, { ignoreSearch: true });
  const fresh = fetch(req)
    .then(res => { if (res && res.ok) cache.put(req, res.clone()); return res; })
    .catch(() => null);
  if (cached) {
    // keep the worker alive until the refresh lands, without delaying paint
    try { event.waitUntil(fresh); } catch (e) {}
    return cached;
  }
  const res = await fresh;
  return res || new Response('Offline', { status: 503 });
}

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;

  let url;
  try { url = new URL(req.url); } catch (e) { return; }
  if (url.origin !== self.location.origin) return;

  // A launch or reload: this is the one that decides whether the user
  // sees today's version or last month's.
  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      try { return await networkFirst(req, 'index.html'); }
      catch (e) {
        const cached = await caches.match('index.html');
        return cached || new Response('Offline', { status: 503 });
      }
    })());
    return;
  }

  if (SHELL_RE.test(url.pathname)) {
    event.respondWith((async () => {
      try { return await networkFirst(req); }
      catch (e) { return new Response('Offline', { status: 503 }); }
    })());
    return;
  }

  if (IMAGE_RE.test(url.pathname)) {
    event.respondWith(staleWhileRevalidate(req, event));
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      const res = await fetch(req);
      if (res.ok) (await caches.open(CACHE)).put(req, res.clone());
      return res;
    } catch (e) {
      return new Response('Offline', { status: 503 });
    }
  })());
});
""" % {
    "version": version,
    "critical": json.dumps(CRITICAL, indent=2),
    "assets": json.dumps(assets, indent=2),
}

with open(_os.path.join(ROOT, "sw.js"), "w", encoding="utf-8") as f:
    f.write(sw)

print(f"sw.js written · {len(assets)} assets "
      f"({len(CRITICAL)} critical) · {total/1024/1024:.2f} MB · cache {version}")
